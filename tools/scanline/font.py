ADVANCE = 6  # glyph width (5) plus one pixel of spacing


def text_width(text, px):
    return (len(text) * ADVANCE - 1) * px


def text_rects(text, x, y, px):
    """Rectangles (x, y, w, h) for `text` with top-left at (x, y), each font pixel px wide.

    Horizontal runs of inked pixels are merged, so a glyph row is one rectangle where possible.
    """
    rects = []
    for i, ch in enumerate(text):
        if ch not in GLYPHS:
            raise KeyError(f"font.py has no glyph for {ch!r}; add it to GLYPHS")
        rows = GLYPHS[ch]
        gx = x + i * ADVANCE * px
        for ry, row in enumerate(rows):
            run = None
            for rx, c in enumerate(row + "."):
                if c == "#" and run is None:
                    run = rx
                elif c != "#" and run is not None:
                    rects.append((gx + run * px, y + ry * px, (rx - run) * px, px))
                    run = None
    return rects


def scanline_text_rects(text, x, y, px, line=None, gap=None):
    """Pixel type drawn as scanlines: each font pixel row becomes two thin horizontal rules."""
    line = line or max(1, px // 4)
    gap = gap or px // 2
    rects = []
    for (rx, ry, rw, _) in text_rects(text, x, y, px):
        rects.append((rx, ry + (gap - line) // 2, rw, line))
        rects.append((rx, ry + gap + (gap - line) // 2, rw, line))
    return rects
